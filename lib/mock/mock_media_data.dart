  static List<MediaItem> recentlyAdded({int days = 3}) {
    final cutoff = DateTime.now().subtract(Duration(days: days));
    return allMedia.where((m) => m.dateAdded.isAfter(cutoff)).toList()
      ..sort((a, b) => a.dateAdded.compareTo(b.dateAdded));
  }
